"""Write dop853_coefficients.h from SciPy's DOP853 tableau, so that the C
stepper and the Python reference share one method. Run from this directory:

    python _generate_dop853_coefficients.py
"""
from pathlib import Path

import numpy as np
from scipy.integrate._ivp import dop853_coefficients as dop853


def array(name, values):
    values = np.asarray(values, float)
    if values.ndim == 1:
        body = ', '.join(f'{v:.17g}' for v in values)
        return f'static const double {name}[{len(values)}] = {{{body}}};'
    rows = ',\n    '.join('{' + ', '.join(f'{v:.17g}' for v in row) + '}' for row in values)
    return f'static const double {name}[{values.shape[0]}][{values.shape[1]}] = {{\n    {rows}}};'


stages = dop853.N_STAGES
lines = ['// Generated by _generate_dop853_coefficients.py from SciPy\'s DOP853 tableau.',
         '#ifndef XTRACK_LORENTZ_REFERENCE_DOP853_H',
         '#define XTRACK_LORENTZ_REFERENCE_DOP853_H',
         f'#define LORENTZ_DOP853_STAGES {stages}',
         array('LORENTZ_DOP853_A', dop853.A[:stages, :stages]),
         array('LORENTZ_DOP853_B', dop853.B),
         array('LORENTZ_DOP853_C', dop853.C[:stages]),
         array('LORENTZ_DOP853_E3', dop853.E3),
         array('LORENTZ_DOP853_E5', dop853.E5),
         '#endif']
Path(__file__).with_name('dop853_coefficients.h').write_text('\n'.join(lines) + '\n')
